"""Moonlight lightmap bake -> public/models/hallway_moon.png  (same UV1 / "AO" atlas as the baked AO)

    blender -b -P blender/bake_moon.py                     # bake (4096, 1024 spp) + encode + preview
    blender -b -P blender/bake_moon.py -- --res 2048 --samples 256    # faster look-dev bake
    blender -b -P blender/bake_moon.py -- --encode-only    # re-encode / re-preview from the cached EXR
    blender -b -P blender/bake_moon.py -- --no-preview
    blender -b -P blender/bake_moon.py -- --encode-only --jpg     # also write hallway_moon.jpg (q95)

Opens blender/_tex/hallway_build.blend (written by hallway.py), so re-run it after every hallway.py rebuild:
the lightmap UVs are regenerated by each build.  hallway.py -- --moon runs it automatically at the end.

Lights match the runtime spots this replaces (src/haunt/scene.js before the bake): one spot per window, 3.2 m
outside along the inward direction (window's inward horizontal, y = -0.25 in glTF, i.e. ~14 deg down), colour
#9fb4e6, 38 cd (side rooms) / 22 cd (end window), cone 0.36 / 0.5 rad, penumbra 0.5.  A three.js point light of
I cd == a Blender light of 4*pi*I W; Cycles' DIFFUSE bake (no Color) returns irradiance / pi.  So with image value
v (linear, after sRGB decode) and SCALE = bake value at v = 1:  runtime irradiance = v * SCALE * pi, i.e.
material.lightMapIntensity = pi * SCALE reproduces the old spots' brightness (plus the bounce they lacked).

Glass, the Outside backdrop, cobwebs, decals, milk glass and shards are hidden for the bake (the runtime glass is
transparent); curtains stay (alpha-clipped, they shadow like the runtime shadow maps did).
"""
import math
import os
import sys
import time

import bpy
import numpy as np
from mathutils import Vector

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import MODELS, link, _enable_gpu  # noqa: E402
import room_tex as RT  # noqa: E402

ARGS = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []


def _arg(name, default):
    return type(default)(ARGS[ARGS.index(name) + 1]) if name in ARGS else default


RES = _arg("--res", 4096)
SAMPLES = _arg("--samples", 1024)
TEXDIR = os.path.join(HERE, "_tex")
BLEND = os.path.join(TEXDIR, "hallway_build.blend")
RAW = os.path.join(TEXDIR, "hallway_moon_raw.exr")
OUT = os.path.join(MODELS, "hallway_moon.png")
PREVIEW = os.path.join(HERE, "hallway_preview_moonbake.png")
BLUR = 1.0                   # denoise blur sigma (texels at 4096; scaled with --res)
PEAK = 0.85                  # brightest moon patches land here (linear, before sRGB encode)

MOON_SRGB = (0x9f, 0xb4, 0xe6)
SIDE_CD, END_CD = 38.0, 22.0
SIDE_ANGLE, END_ANGLE = 0.36, 0.5    # three.js SpotLight.angle (half angle, rad)
PENUMBRA = 0.5
BACK = 3.2                   # light distance outside the window
SOFT = 0.12                  # light radius (m): soft-ish shadow edges

HIDE_PREFIX = ("Outside", "WindowGlass_", "Cobwebs", "Decals", "CeilingFixtures_Glass", "Glass_Shards", "COL_")


def srgb_to_lin(c):
    c = c / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def lin_to_srgb(x):
    x = np.clip(x, 0.0, 1.0)
    return np.where(x <= 0.0031308, 12.92 * x, 1.055 * np.power(x, 1 / 2.4) - 0.055)


def is_target(o):
    """Meshes whose every material carries the AO occlusion map (= gets the lightmap at runtime)."""
    if o.type != "MESH" or o.name.startswith(HIDE_PREFIX) or "AO" not in o.data.uv_layers:
        return False
    ms = [m for m in o.data.materials if m]
    return bool(ms) and all(m.node_tree and any(n.type == "GROUP" for n in m.node_tree.nodes) for m in ms)


def moon_spots():
    for o in list(bpy.data.objects):
        if o.type == "LIGHT":
            bpy.data.objects.remove(o, do_unlink=True)
    col = tuple(srgb_to_lin(c) for c in MOON_SRGB)
    out = []
    for e in bpy.data.objects:
        if e.type != "EMPTY" or not (e.name.startswith("Window_L") or e.name.startswith("Window_R") or e.name == "Window_End"):
            continue
        end = e.name == "Window_End"
        d = e.matrix_world.to_3x3() @ Vector((0, 1, 0))          # local +Y (glTF local -Z) = out towards the moon
        inward = Vector((-d.x, -d.y, 0)).normalized()
        inward.z = -0.25
        inward.normalize()
        ld = bpy.data.lights.new("MoonBake_" + e.name, "SPOT")
        ld.color = col
        ld.energy = 4 * math.pi * (END_CD if end else SIDE_CD)
        ang = END_ANGLE if end else SIDE_ANGLE
        ld.spot_size = 2 * ang
        ld.spot_blend = PENUMBRA
        ld.shadow_soft_size = SOFT
        if hasattr(ld, "use_soft_falloff"):
            ld.use_soft_falloff = False
        lo = link(bpy.data.objects.new("MoonBake_" + e.name, ld))
        lo.location = e.matrix_world.translation - inward * BACK
        lo.rotation_euler = inward.to_track_quat("-Z", "Y").to_euler()
        out.append(lo)
    print(f"[moon] {len(out)} spots")
    return out


def bake():
    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.device = "GPU" if _enable_gpu() else "CPU"
    scene.cycles.samples = SAMPLES
    scene.cycles.use_denoising = False
    c = scene.cycles
    c.max_bounces, c.diffuse_bounces, c.glossy_bounces, c.transmission_bounces = 6, 3, 1, 2
    c.transparent_max_bounces = 16
    c.sample_clamp_direct, c.sample_clamp_indirect = 0.0, 0.3
    scene.world = None                      # no sky light: the moon spots are the only source

    targets = []
    for o in bpy.data.objects:
        if o.type == "MESH" and o.name.startswith(HIDE_PREFIX):
            o.hide_render = True
        if is_target(o):
            targets.append(o)
    print(f"[moon] {len(targets)} bake targets")
    moon_spots()

    img = bpy.data.images.new("Hallway_Moon", RES, RES, alpha=True, float_buffer=True)
    img.colorspace_settings.name = "Non-Color"
    mats = {m for o in targets for m in o.data.materials if m}
    tmp = []
    for m in mats:
        n = m.node_tree.nodes.new("ShaderNodeTexImage")
        n.image = img
        m.node_tree.nodes.active = n
        tmp.append((m, n))
    bpy.ops.object.select_all(action="DESELECT")
    for o in targets:
        o.data.uv_layers.active = o.data.uv_layers["AO"]
        o.data.uv_layers["UVMap"].active_render = True
        o.select_set(True)
    bpy.context.view_layer.objects.active = targets[0]
    t0 = time.time()
    bpy.ops.object.bake(type="DIFFUSE", pass_filter={"DIRECT", "INDIRECT"}, margin=12, margin_type="EXTEND",
                        use_clear=True, target="IMAGE_TEXTURES")
    print(f"[moon] bake {RES}^2 @ {SAMPLES} spp: {time.time() - t0:.0f}s")
    img.filepath_raw = RAW
    img.file_format = "OPEN_EXR"
    img.save()
    for m, n in tmp:
        m.node_tree.nodes.remove(n)
    for o in targets:
        o.data.uv_layers.active = o.data.uv_layers["UVMap"]


def encode():
    img = bpy.data.images.load(RAW, check_existing=False)
    img.colorspace_settings.name = "Non-Color"
    w, h = img.size
    a = np.array(img.pixels[:], dtype=np.float32).reshape(h, w, 4)
    rgb = a[..., :3].astype(np.float64)
    bpy.data.images.remove(img)
    # light denoise: sigma ~1 texel (~7 mm). Islands are >= 6 px apart and the 12 px EXTEND margin fills the gaps,
    # so this does not mix neighbouring islands; the moon's penumbrae are many texels wide, so they stay put.
    for k in range(3):
        rgb[..., k] = RT.blur(rgb[..., k], BLUR * w / 4096)
    rgb = np.maximum(rgb, 0.0)
    # normalise on the largest channel (blue, for this moon colour) so the patches don't clip in blue
    mx = rgb.max(axis=2)
    lit = mx[mx > 1e-4]
    scale = float(np.percentile(lit, 99.7)) / PEAK
    print(f"[moon] max-channel max {mx.max():.4f}  p99 {np.percentile(lit, 99):.4f}  p99.7 {np.percentile(lit, 99.7):.4f}"
          f"  lit texels {lit.size / mx.size * 100:.1f}%")
    v = rgb / scale
    clipped = (v.max(axis=2) > 1).mean() * 100
    enc = lin_to_srgb(v)
    out = bpy.data.images.new("moon_out", w, h, alpha=False, float_buffer=False)
    px = np.ones((h, w, 4), dtype=np.float32)
    px[..., :3] = np.round(enc * 255) / 255
    out.pixels.foreach_set(px.ravel())
    out.filepath_raw = OUT
    out.file_format = "PNG"
    out.save()
    if "--jpg" in ARGS:       # smaller alternative, same encoding
        jpg = OUT[:-4] + ".jpg"
        out.filepath_raw = jpg
        out.file_format = "JPEG"
        bpy.context.scene.render.image_settings.quality = 95
        out.save(quality=95)
        print(f"[moon] {jpg}: {os.path.getsize(jpg) / 1e6:.2f} MB")
    bpy.data.images.remove(out)
    print(f"[moon] {OUT}: {w}x{h}, {os.path.getsize(OUT) / 1e6:.2f} MB, clipped {clipped:.3f}% texels")
    print(f"[moon] SCALE = {scale:.6f} (Blender diffuse-bake units at image value 1.0)  "
          f"-> lightMapIntensity = pi*SCALE = {math.pi * scale:.4f} to match the old 38/22 cd spots")
    return scale


def preview():
    """Runtime camera, every bake target shows only the lightmap (emission), nothing else."""
    scene = bpy.context.scene
    for o in list(bpy.data.objects):
        if o.type == "LIGHT":
            bpy.data.objects.remove(o, do_unlink=True)
    img = bpy.data.images.load(OUT, check_existing=False)
    img.colorspace_settings.name = "sRGB"
    m = bpy.data.materials.new("MoonPreview")
    nt = m.node_tree
    for n in list(nt.nodes):
        nt.nodes.remove(n)
    uv = nt.nodes.new("ShaderNodeUVMap")
    uv.uv_map = "AO"
    tx = nt.nodes.new("ShaderNodeTexImage")
    tx.image = img
    tx.interpolation = "Linear"
    em = nt.nodes.new("ShaderNodeEmission")
    mo = nt.nodes.new("ShaderNodeOutputMaterial")
    nt.links.new(uv.outputs["UV"], tx.inputs["Vector"])
    nt.links.new(tx.outputs["Color"], em.inputs["Color"])
    nt.links.new(em.outputs["Emission"], mo.inputs["Surface"])
    for o in bpy.data.objects:
        if o.type == "MESH":
            if is_target(o):
                o.hide_render = False
                o.data.materials.clear()      # in-memory only, the .blend is never saved
                o.data.materials.append(m)
                for p in o.data.polygons:
                    p.material_index = 0
            else:
                o.hide_render = True
    scene.world = None
    cd = bpy.data.cameras.new("MoonCam")
    cd.sensor_fit = "VERTICAL"
    cd.angle_y = math.radians(50)
    cd.clip_start = 0.05
    cam = link(bpy.data.objects.new("MoonCam", cd))
    bl = lambda p: Vector((p[0], -p[2], p[1]))
    cam.location = bl((0.3, 1.6, 0.2))
    cam.rotation_euler = (bl((-0.1, 1.2, -14.0)) - cam.location).to_track_quat("-Z", "Y").to_euler()
    scene.camera = cam
    scene.render.resolution_x, scene.render.resolution_y = 1728, 1117
    scene.render.resolution_percentage = 100
    scene.render.engine = "CYCLES"
    scene.cycles.device = "GPU" if _enable_gpu() else "CPU"
    scene.cycles.samples = 16
    scene.cycles.max_bounces = 0
    scene.cycles.use_denoising = False
    scene.view_settings.view_transform = "Standard"
    scene.view_settings.look = "None"
    scene.view_settings.exposure = 0.0
    scene.render.image_settings.file_format = "PNG"
    scene.render.filepath = PREVIEW
    bpy.ops.render.render(write_still=True)
    print(f"[moon] preview {PREVIEW}")


def run(open_blend=True):
    if open_blend:
        bpy.ops.wm.open_mainfile(filepath=BLEND)
    if "--encode-only" not in ARGS:
        bake()
    encode()
    if "--no-preview" not in ARGS:
        preview()


if __name__ == "__main__":
    run()
